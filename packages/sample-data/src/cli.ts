// Writes the fixtures to packages/sample-data/fixtures (run: pnpm --filter @venzini/sample-data generate).
import { mkdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { generateFixtures } from './fixtures';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', 'fixtures');
const write = (file: string, data: unknown) => {
  mkdirSync(dirname(join(root, file)), { recursive: true });
  writeFileSync(join(root, file), `${JSON.stringify(data, null, 2)}\n`);
};

const f = generateFixtures();
rmSync(root, { recursive: true, force: true });
write('demo.json', f.demo);
write('reference.json', f.reference);
write('users.json', f.users);
write('stations.json', f.stations);
write('network.json', f.network);
for (const fc of f.forecasts) write(`forecasts/${fc.station_id}-${fc.fuel_type_id}.json`, fc);
write('totals.json', f.totals);
write('resources.json', f.resources);
write('plans/optimal.json', f.optimal);
write('plans/scripted-edits.json', f.scriptedEdits);
write('trips.json', f.trips);
write('decisions.json', f.decisions);

// index.ts gathers every file into one typed-free object for the web app's mock API.
const forecastImports = f.forecasts.map(
  (fc, i) => `import fc${i} from './forecasts/${fc.station_id}-${fc.fuel_type_id}.json';`,
);
const index = `// Generated by src/cli.ts — do not edit. Fake sample data only (SDD 7.2).
import decisions from './decisions.json';
import demo from './demo.json';
import network from './network.json';
import optimal from './plans/optimal.json';
import scriptedEdits from './plans/scripted-edits.json';
import reference from './reference.json';
import resources from './resources.json';
import stations from './stations.json';
import totals from './totals.json';
import trips from './trips.json';
import users from './users.json';
${forecastImports.join('\n')}

export const rawFixtures = {
  demo,
  reference,
  users,
  stations,
  network,
  forecasts: [${f.forecasts.map((_, i) => `fc${i}`).join(', ')}],
  totals,
  resources,
  optimal,
  scriptedEdits,
  trips,
  decisions,
};
`;
writeFileSync(join(root, 'index.ts'), index);
console.log(`Fixtures written to ${root}`);
